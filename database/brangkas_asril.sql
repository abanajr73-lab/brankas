CREATE DATABASE IF NOT EXISTS brangkas_asril CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE brangkas_asril;
CREATE TABLE app_settings(setting_name VARCHAR(100) NOT NULL PRIMARY KEY,setting_value TEXT NOT NULL) ENGINE=InnoDB;
CREATE TABLE vault_contents(id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,title VARCHAR(150) NOT NULL,ciphertext LONGTEXT NOT NULL COMMENT 'AES-256-GCM Base64',iv VARCHAR(64) NOT NULL,auth_tag VARCHAR(64) NOT NULL,created_at DATETIME NOT NULL) ENGINE=InnoDB;
